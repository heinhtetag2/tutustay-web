export const NRC_TYPES = ["N", "E", "P"] as const;
export type NrcType = (typeof NRC_TYPES)[number];

const PATTERN = /^(\d{1,2})\/([A-Za-z]+)\((N|E|P)\)(\d{6})$/;

export interface NrcParts { state: number | null; township: string; type: NrcType | ""; number: string }
export const EMPTY_NRC: NrcParts = { state: null, township: "", type: "", number: "" };

export function parseNrc(value: string): NrcParts {
  const m = value.trim().match(PATTERN);
  if (!m) return EMPTY_NRC;
  const state = Number(m[1]);
  // Match the township code ignoring letter case, so "MAKANA" and "MaKaNa" are the same place.
  const township = NRC_TOWNSHIPS.find((r) => r[0] === state && r[1].toLowerCase() === m[2]!.toLowerCase())?.[1] ?? m[2]!;
  return { state, township, type: m[3] as NrcType, number: m[4]! };
}

/** The written form, or "" until every part is chosen and the number has 6 digits. */
export function formatNrc(p: NrcParts): string {
  return p.state && p.township && p.type && /^\d{6}$/.test(p.number) ? `${p.state}/${p.township}(${p.type})${p.number}` : "";
}
